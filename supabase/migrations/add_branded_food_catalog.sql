-- Shared branded-food catalog for fast search on mobile networks.
-- Catalog writes are service-role only; catalog reads are public nutrition data.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS public.branded_foods (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  brand TEXT,
  barcode TEXT,
  serving_size DECIMAL(12,3),
  serving_unit TEXT NOT NULL DEFAULT 'serving',
  serving_description TEXT,
  calories DECIMAL(12,3) NOT NULL DEFAULT 0,
  protein DECIMAL(12,3) NOT NULL DEFAULT 0,
  fat DECIMAL(12,3) NOT NULL DEFAULT 0,
  carbs DECIMAL(12,3) NOT NULL DEFAULT 0,
  fiber DECIMAL(12,3) NOT NULL DEFAULT 0,
  image_url TEXT,
  market_country TEXT NOT NULL DEFAULT 'US',
  source TEXT NOT NULL,
  source_id TEXT NOT NULL,
  source_license TEXT,
  data_quality SMALLINT NOT NULL DEFAULT 0,
  last_synced_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  CONSTRAINT branded_foods_source_check
    CHECK (source IN ('usda', 'open_food_facts')),
  CONSTRAINT branded_foods_data_quality_check
    CHECK (data_quality BETWEEN 0 AND 100),
  CONSTRAINT branded_foods_source_unique UNIQUE (source, source_id)
);

CREATE INDEX IF NOT EXISTS idx_branded_foods_name_trgm
  ON public.branded_foods USING GIN (LOWER(name) gin_trgm_ops);

CREATE INDEX IF NOT EXISTS idx_branded_foods_brand_trgm
  ON public.branded_foods USING GIN (LOWER(COALESCE(brand, '')) gin_trgm_ops);

CREATE INDEX IF NOT EXISTS idx_branded_foods_barcode
  ON public.branded_foods (barcode)
  WHERE barcode IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_branded_foods_country_quality
  ON public.branded_foods (market_country, data_quality DESC);

ALTER TABLE public.branded_foods ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can search branded foods" ON public.branded_foods;
CREATE POLICY "Anyone can search branded foods"
  ON public.branded_foods
  FOR SELECT
  USING (TRUE);

-- Catalog rows are never directly inserted or changed by anon/authenticated users.
-- Supabase's service role bypasses RLS for import jobs.

DROP TRIGGER IF EXISTS update_branded_foods_updated_at ON public.branded_foods;
CREATE TRIGGER update_branded_foods_updated_at
  BEFORE UPDATE ON public.branded_foods
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

CREATE OR REPLACE FUNCTION public.search_branded_foods(
  search_query TEXT,
  result_limit INTEGER DEFAULT 20
)
RETURNS TABLE (
  id BIGINT,
  name TEXT,
  brand TEXT,
  barcode TEXT,
  serving_size DECIMAL,
  serving_unit TEXT,
  serving_description TEXT,
  calories DECIMAL,
  protein DECIMAL,
  fat DECIMAL,
  carbs DECIMAL,
  fiber DECIMAL,
  image_url TEXT,
  source TEXT,
  source_id TEXT,
  data_quality SMALLINT,
  rank REAL
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT
    food.id,
    food.name,
    food.brand,
    food.barcode,
    food.serving_size,
    food.serving_unit,
    food.serving_description,
    food.calories,
    food.protein,
    food.fat,
    food.carbs,
    food.fiber,
    food.image_url,
    food.source,
    food.source_id,
    food.data_quality,
    (
      CASE
        WHEN LOWER(food.name) = LOWER(TRIM(search_query)) THEN 4.0
        WHEN LOWER(food.name) LIKE LOWER(TRIM(search_query)) || '%' THEN 3.0
        WHEN LOWER(COALESCE(food.brand, '')) LIKE LOWER(TRIM(search_query)) || '%' THEN 2.0
        ELSE 0.0
      END
      + similarity(LOWER(food.name), LOWER(TRIM(search_query))) * 2.0
      + similarity(LOWER(COALESCE(food.brand, '')), LOWER(TRIM(search_query)))
      + food.data_quality::REAL / 500.0
    )::REAL AS rank
  FROM public.branded_foods AS food
  WHERE LENGTH(TRIM(search_query)) >= 2
    AND food.market_country IN ('US', 'CA')
    AND (
      LOWER(food.name) LIKE '%' || LOWER(TRIM(search_query)) || '%'
      OR LOWER(COALESCE(food.brand, '')) LIKE '%' || LOWER(TRIM(search_query)) || '%'
      OR LOWER(food.name) % LOWER(TRIM(search_query))
      OR LOWER(COALESCE(food.brand, '')) % LOWER(TRIM(search_query))
    )
  ORDER BY rank DESC, food.name ASC
  LIMIT LEAST(GREATEST(result_limit, 1), 50);
$$;

REVOKE ALL ON FUNCTION public.search_branded_foods(TEXT, INTEGER) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.search_branded_foods(TEXT, INTEGER) TO anon, authenticated;

-- Preserve the source and confidence of manually entered / camera-estimated foods.
ALTER TABLE public.foods
  ADD COLUMN IF NOT EXISTS branded_food_id BIGINT
    REFERENCES public.branded_foods(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS entry_source TEXT NOT NULL DEFAULT 'manual',
  ADD COLUMN IF NOT EXISTS estimate_confidence DECIMAL(4,3);

ALTER TABLE public.food_log
  ADD COLUMN IF NOT EXISTS entry_source TEXT NOT NULL DEFAULT 'manual',
  ADD COLUMN IF NOT EXISTS estimate_confidence DECIMAL(4,3);

DO $$ BEGIN
  ALTER TABLE public.foods
    ADD CONSTRAINT foods_entry_source_check
    CHECK (entry_source IN ('manual', 'catalog', 'barcode', 'nfp_scan', 'photo_estimate'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE public.food_log
    ADD CONSTRAINT food_log_entry_source_check
    CHECK (entry_source IN ('manual', 'catalog', 'barcode', 'nfp_scan', 'photo_estimate'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE public.foods
    ADD CONSTRAINT foods_estimate_confidence_check
    CHECK (estimate_confidence IS NULL OR estimate_confidence BETWEEN 0 AND 1);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  ALTER TABLE public.food_log
    ADD CONSTRAINT food_log_estimate_confidence_check
    CHECK (estimate_confidence IS NULL OR estimate_confidence BETWEEN 0 AND 1);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
